namespace Adeni.Application.Reporting;

using Adeni.Application.Auth;
using Adeni.Application.Finance;
using Adeni.Application.Subscriptions;
using Adeni.Application.Tenancy;
using Adeni.Domain.Common;
using Adeni.Domain.Identity;

public sealed class DocumentPreviewService(IPortalTenantAccessQuery access, IBillingDocumentService documents,
    IDocumentBookingScopeQuery bookings, ITenantLocationScopeService locations, IEntitlementsService entitlements,
    IBillingDocumentPreviewSource source) : IDocumentPreviewService
{
    public const int MaxBytes = 5 * 1024 * 1024;

    public async Task<Result<DocumentPreview>> GetAsync(Guid tenantId, Guid documentId, string actor, Guid? locationId, CancellationToken ct)
    {
        var user = await access.ResolveAsync(tenantId, actor, ct);
        if (user.IsFailure || !user.Value!.Permissions.Any(x => x is BusinessPermissions.Finance or BusinessPermissions.Bookings))
            return Result.Failure<DocumentPreview>(ErrorCodes.PermissionDeniedError());
        var entitlement = await entitlements.GetEntitlementsForMemberAsync(tenantId, actor, ct);
        if (entitlement.IsFailure) return Result.Failure<DocumentPreview>(entitlement.Error);
        if (!entitlement.Value!.InvoicesReceipts) return Result.Failure<DocumentPreview>(ErrorCodes.PermissionDeniedError());
        var resolved = await locations.ResolveListLocationAsync(tenantId, locationId, ct);
        if (resolved.IsFailure) return Result.Failure<DocumentPreview>(resolved.Error);
        var result = await documents.GetAsync(documentId, ct);
        if (result.IsFailure) return Result.Failure<DocumentPreview>(result.Error);
        var doc = result.Value!;
        if (doc.TenantId != tenantId) return Result.Failure<DocumentPreview>(ErrorCodes.PermissionDeniedError());
        if (doc.Status == "void")
            return Result.Failure<DocumentPreview>(Error.Conflict("Voided documents cannot be downloaded."));
        if (doc.BookingId is not Guid bookingId || doc.Kind is not ("receipt" or "invoice") || doc.Status is not ("draft" or "issued"))
            return Result.Failure<DocumentPreview>(Error.Validation("Preview requires a non-void booking receipt or invoice."));
        var branch = await bookings.GetLocationAsync(tenantId, bookingId, ct);
        if (branch.IsFailure || (resolved.Value is Guid allowed && branch.Value != allowed))
            return Result.Failure<DocumentPreview>(ErrorCodes.PermissionDeniedError());
        ct.ThrowIfCancellationRequested();
        var bytes = await source.RenderAsync(documentId, ct);
        if (bytes.IsFailure) return Result.Failure<DocumentPreview>(bytes.Error);
        if (bytes.Value!.Length > MaxBytes)
            return Result.Failure<DocumentPreview>(Error.Validation("Document exceeds the private viewer limit."));
        // Identifiers generated by the server, without customer data or arbitrary filename characters.
        return Result.Success(new DocumentPreview(bytes.Value, $"{doc.Kind}-{doc.Id:N}.pdf"));
    }
}
